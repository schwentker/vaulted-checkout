// Builds reactors/signer/reactor.js (single file for Basis Theory) from the contract reference + signer body.
//   node scripts/build-signer.mjs          write the file
//   node scripts/build-signer.mjs --check  fail if the committed file is stale
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url);
const core = readFileSync(new URL('contracts/reference/intent-core.cjs', root), 'utf8')
  .replace(/^'use strict';\n/, '')
  .replace(/module\.exports = \{[\s\S]*?\};\s*$/, '');
const main = readFileSync(new URL('reactors/signer/main.js', root), 'utf8');
const out = `'use strict';\n// GENERATED by scripts/build-signer.mjs. Do not edit. Source: contracts/reference/intent-core.cjs + reactors/signer/main.js\n\n${core}\n${main}`;
const target = new URL('reactors/signer/reactor.js', root);
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(target, 'utf8'); } catch {}
  if (cur !== out) { console.error('reactors/signer/reactor.js is stale; run node scripts/build-signer.mjs'); process.exit(1); }
  console.log('signer reactor up to date');
} else { writeFileSync(target, out); console.log('wrote reactors/signer/reactor.js', out.length, 'bytes'); }
