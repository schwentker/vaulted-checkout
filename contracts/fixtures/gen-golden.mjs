// Regenerates contracts/fixtures/golden-attempt.json.
// Uses PUBLIC Hardhat test keys and a PUBLIC test MAC key. Never put a real key here.
// Run from a workspace that has viem@2.57.11 and @x402/core@2.28.0 installed:
//   node contracts/fixtures/gen-golden.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { privateKeyToAccount } from 'viem/accounts';
import { getAddress, recoverTypedDataAddress } from 'viem';
import { encodePaymentSignatureHeader, encodePaymentRequiredHeader } from '@x402/core/http';

const require = createRequire(import.meta.url);
const core = require('../reference/intent-core.cjs');

const HARDHAT_0_PK = '0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80'; // public test key
const MERCHANT = '0x70997970C51812dc3A010C7d01b50e0d17dc79C8'; // Hardhat #1, public
const TEST_MAC_KEY = 'public-test-intent-key-not-a-secret';
const NOW = 1793000000;

const account = privateKeyToAccount(HARDHAT_0_PK);
const cfg = {
  AUDIENCE: 'vc-signer', CHAIN_ID: '84532', ASSET: '0x036CbD53842c5426634e7929541eC2318f3dCF7e',
  DOMAIN_NAME: 'USDC', DOMAIN_VERSION: '2', WALLET_ADDRESS: account.address, PAYTO_ALLOWLIST: MERCHANT,
  POLICY_VERSION: 'p1', MAX_AMOUNT: '5000000', MAX_WINDOW_SECONDS: '600',
};

const resource = { url: 'https://merchant.example/api/orders/ord_golden_1/pay', description: 'Order ord_golden_1', mimeType: 'application/json' };
const accepted = {
  scheme: 'exact', network: 'eip155:84532', asset: cfg.ASSET, amount: '1500000', payTo: MERCHANT,
  maxTimeoutSeconds: 300, extra: { name: 'USDC', version: '2' },
};
const paymentRequired = { x402Version: 2, error: 'Payment required', resource, accepts: [accepted] };

const intent = {
  v: 'vc-intent-1', audience: 'vc-signer', order_id: 'ord_golden_1', attempt_id: '7c9e6679-7425-40de-944b-e07fc1f90ae7',
  chain_id: '84532', asset: cfg.ASSET, from: account.address, to: MERCHANT, value: '1500000',
  valid_after: '0', valid_before: String(NOW + 300),
  nonce: '0x' + '11'.repeat(32), policy_version: 'p1', issued_at: String(NOW),
};

const mac = core.macIntent(intent, TEST_MAC_KEY);
if (!core.verifyMac(intent, mac, TEST_MAC_KEY)) throw new Error('mac roundtrip failed');
const rule = core.checkRules(intent, cfg, NOW);
if (rule) throw new Error('golden intent fails rule ' + rule);

const td = core.typedDataFor(intent, cfg, getAddress);
const sig1 = await account.signTypedData(td);
const sig2 = await account.signTypedData(td);
if (sig1 !== sig2) throw new Error('signing is not deterministic; retry contract broken');
const recovered = await recoverTypedDataAddress({ ...td, signature: sig1 });
if (recovered !== account.address) throw new Error('recover mismatch');

const paymentPayload = {
  x402Version: 2,
  resource,
  accepted,
  payload: {
    authorization: {
      from: account.address, to: MERCHANT, value: intent.value,
      validAfter: intent.valid_after, validBefore: intent.valid_before, nonce: intent.nonce,
    },
    signature: sig1,
  },
};

// Negative cases: each must fail with the listed code.
const neg = (patch, code, cfgPatch = {}) => ({ patch, cfg_patch: cfgPatch, expect: code });
const negatives = [
  neg({ chain_id: '8453' }, 'rule_chain'),
  neg({ asset: '0x0000000000000000000000000000000000000001' }, 'rule_asset'),
  neg({ to: '0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC' }, 'rule_payto'),
  neg({ value: '5000001' }, 'rule_amount'),
  neg({ value: '0' }, 'rule_amount'),
  neg({ valid_before: String(NOW + 601) }, 'rule_window'),
  neg({ valid_before: String(NOW - 1) }, 'rule_window'),
  neg({ issued_at: String(NOW - 601) }, 'stale_intent'),
  neg({ policy_version: 'p0' }, 'rule_policy'),
  neg({ from: MERCHANT }, 'rule_from'),
  neg({ audience: 'someone-else' }, 'rule_audience'),
  neg({ nonce: '0x11' }, 'bad_request'),
  neg({ valid_after: String(NOW + 86400), valid_before: String(NOW + 86460) }, 'rule_window'),
  neg({ valid_after: String(NOW) }, 'rule_window'),
  neg({ issued_at: String(NOW + 61) }, 'stale_intent'),
  neg({ value: '9'.repeat(78) }, 'bad_request'),
  neg({ extra: 'not allowed' }, 'bad_request'),
];
for (const n of negatives) {
  const got = core.checkRules({ ...intent, ...n.patch }, { ...cfg, ...n.cfg_patch }, NOW);
  if (got !== n.expect) throw new Error(`negative ${JSON.stringify(n.patch)} expected ${n.expect} got ${got}`);
}

const golden = {
  _note: 'Generated by gen-golden.mjs. PUBLIC test keys only. Do not hand edit.',
  now: NOW,
  reactor_config: { ...cfg, INTENT_HMAC_KEY: TEST_MAC_KEY, WALLET_TOKEN_ID: '<fixture: key is HARDHAT_0_PK in gen-golden.mjs>' },
  payment_required: paymentRequired,
  payment_required_header: encodePaymentRequiredHeader(paymentRequired),
  intent,
  canonical_intent: core.canonicalize(intent),
  intent_mac: mac,
  signer_request: { intent, intent_mac: mac },
  typed_data: { ...td, message: { ...td.message, value: intent.value, validAfter: intent.valid_after, validBefore: intent.valid_before } },
  signer_response: { statusCode: 200, body: { ok: true, from: account.address, signature: sig1, attempt_id: intent.attempt_id } },
  payment_payload: paymentPayload,
  payment_signature_header: encodePaymentSignatureHeader(paymentPayload),
  negatives,
};
writeFileSync(new URL('./golden-attempt.json', import.meta.url), JSON.stringify(golden, null, 2) + '\n');
console.log('golden ok', { from: account.address, sig: sig1.slice(0, 12) + '...' });
